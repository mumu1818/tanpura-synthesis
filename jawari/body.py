def body_modes(preset="tanpura", sr=44100, seed=0, n_mics=1, **overrides):
    """Return the modal parameters: dict(f, sigma, amp[(K, n_mics)], family, explicit mask, params, derived)."""
    p = get_params(preset, **overrides)
    if p.get("none"):
        raise ValueError("preset 'none' has no modes")
    d = derived(p)
    rng = np.random.default_rng(seed)
    f_top = min(p["f_top"], 0.45 * sr)
    fam_names = ("plate", "shell", "cav")
    shares = dict(plate=p["share_plate"], shell=p["share_shell"], cav=p["share_cav"])
    # --- dense modes
    fg = np.linspace(p["dense_f0"], f_top, int((f_top - p["dense_f0"]) / 0.5) + 1)
    nd = densities(fg, p, d)
    nd = {k: np.minimum(v, p["max_density"]) for k, v in nd.items()}
    act_share = sum(shares[k] * (nd[k] > 0) for k in fam_names)
    F, SIG, AMP, FAM = [], [], [], []
    G2 = 10 ** (envelope_db(fg, p, d) / 10)
    ramp = _smoothstep_log(fg, p["dense_f0"], p["dense_f1"])
    for k in fam_names:
        n = nd[k]
        if shares[k] <= 0 or np.all(n <= 0):
            continue
        N = np.concatenate([[0.0], np.cumsum(0.5 * (n[1:] + n[:-1]) * np.diff(fg))])
        K = int(np.floor(N[-1]))
        if K < 1:
            continue
        u = np.arange(K) + 0.5 + p["jitter"] * (rng.random(K) - 0.5)
        fk = np.interp(u, N, fg)
        nk = np.interp(fk, fg, n)
        ok = nk > 0
        fk, nk = fk[ok], nk[ok]
        if k == "plate":
            eta = eta_plate(fk, p, d)
        elif k == "shell":
            eta = p["eta_shell"] * (fk / 1000.0) ** p["eta_exp"] + 0.0 * fk
        else:
            eta = np.full_like(fk, 1.0 / p["Q_cav"])
        eta = eta * np.exp(p["q_scatter"] * rng.standard_normal(fk.size))
        sig = np.pi * fk * eta
        share = shares[k] / np.interp(fk, fg, act_share)
        # E|H|^2 = n A^2 / (8 sigma)  ->  A = G sqrt(8 sigma share / n)
        A = np.sqrt(np.interp(fk, fg, G2) * 8 * sig * share / nk) * np.interp(fk, fg, ramp)
        g1 = rng.standard_normal(fk.size)
        cols = [g1]
        for _m in range(1, n_mics):
            cols.append(p["rho_mics"] * g1 + np.sqrt(1 - p["rho_mics"] ** 2) * rng.standard_normal(fk.size))
        F.append(fk); SIG.append(sig); AMP.append(A[:, None] * np.stack(cols, 1)); FAM += [k] * fk.size
    # --- explicit low modes
    ex_f, ex_sig, ex_amp, ex_names = [], [], [], []
    for (name, fam, f0, Q, gdb, s2) in (p["modes"] if p["modes"] is not None else explicit_modes(p)):
        fk = f0 * (p["air_scale"] if fam == "air" else p["plate_scale"])
        if fk >= 0.45 * sr:
            continue
        sig = np.pi * fk / Q
        A = 10 ** ((gdb + p["mode_gain_db"]) / 20) * 2 * sig      # peak |H| = A / (2 sigma)
        row = [A]
        for _m in range(1, n_mics):
            jit = 10 ** (p["mic2_gain_jitter_db"] * rng.standard_normal() / 20)
            row.append(A * s2 * jit)
        ex_f.append(fk); ex_sig.append(sig); ex_amp.append(row); ex_names.append(name)
    f_all = np.concatenate(F + [np.array(ex_f)]) if F else np.array(ex_f)
    s_all = np.concatenate(SIG + [np.array(ex_sig)]) if SIG else np.array(ex_sig)
    a_all = np.concatenate(AMP + [np.array(ex_amp).reshape(-1, n_mics)], 0) if AMP else np.array(ex_amp)
    fam_all = np.array(FAM + ["explicit"] * len(ex_f))
    return dict(f=f_all, sigma=s_all, amp=a_all, family=fam_all, explicit_names=ex_names,
                explicit=fam_all == "explicit", params=p, derived=d, f_top=f_top)


@njit(cache=True)
def _modal_ir(N, f, sig, amp, sr):
    """sum_k amp[k, c] exp(-sig_k t) sin(omega_dk t), exact (impulse-invariant) via a 2-pole recursion,
    each mode computed only until it has decayed by 120 dB."""
    K, C = amp.shape
    out = np.zeros((N, C))
    for k in range(K):
        w0 = 2.0 * np.pi * f[k]
        wd = np.sqrt(max(w0 * w0 - sig[k] * sig[k], 1e-12)) / sr
        r = np.exp(-sig[k] / sr)
        L = min(N, int(13.8155 / sig[k] * sr) + 2)
        c1 = 2.0 * r * np.cos(wd)
        c2 = r * r
        s2 = 0.0
        s1 = r * np.sin(wd)
        for c in range(C):
            out[1, c] += amp[k, c] * s1
        for n in range(2, L):
            s0 = c1 * s1 - c2 * s2
            for c in range(C):
                out[n, c] += amp[k, c] * s0
            s2 = s1
            s1 = s0
    return out


def body_ir(preset="tanpura", sr=44100, seed=0, n_mics=1, **overrides):
    """Body impulse response(s), shape (N, n_mics), unit-energy per channel on average, causal.

    explicit low modes: ACCELERATION-type (far-field pressure of a monopole-like mode, p/F ~ -w^2 / (w_k^2 - w^2
        + j w w_k / Q)): +12 dB/oct below each mode, flat (mass-like) above. Their flat high-frequency asymptote is
        rolled off by a 2nd-order low-pass at explicit_lp_hz, where the dense region takes over (no double count).
    dense modes: displacement-type damped sines with random-sign residues, high-passed (2nd order) at
        dense_hp_hz (their incoherent low-frequency skirts are not part of the low-frequency model).
    The sum is high-passed at hp_hz (order hp_order) as a DC / rumble guard."""
    md = body_modes(preset, sr, seed, n_mics, **overrides)
    p = md["params"]
    N = int(p["ir_dur"] * sr)
    ex = md["explicit"]
    f = md["f"].astype(np.float64)
    sg = md["sigma"].astype(np.float64)
    amp = np.ascontiguousarray(md["amp"], dtype=np.float64)
    h = np.zeros((N, n_mics))
    if np.any(~ex):
        hd = _modal_ir(N, f[~ex], sg[~ex], np.ascontiguousarray(amp[~ex]), float(sr))
        if p["dense_hp_hz"] > 0:
            hd = ss.sosfilt(ss.butter(2, p["dense_hp_hz"], "highpass", fs=sr, output="sos"), hd, axis=0)
        h += hd
    if np.any(ex):
        w2 = (2 * np.pi * f[ex]) ** 2
        he = _modal_ir(N + 1, f[ex], sg[ex], np.ascontiguousarray(amp[ex] / w2[:, None]), float(sr))
        hp_ = np.concatenate([np.zeros((1, n_mics)), he])          # h[-1] = 0
        # central second difference * sr^2  = d^2/dt^2 (error < 0.2 % below 1.5 kHz); h[0] = 0 keeps it causal
        he = -(hp_[2:] - 2 * hp_[1:-1] + hp_[:-2]) * sr ** 2
        if p["explicit_lp_hz"] > 0:
            he = ss.sosfilt(ss.butter(2, p["explicit_lp_hz"], "lowpass", fs=sr, output="sos"), he, axis=0)
        h += he
    if p["hp_hz"] and p["hp_hz"] > 0:
        sos = ss.butter(p["hp_order"], p["hp_hz"], "highpass", fs=sr, output="sos")
        h = ss.sosfilt(sos, h, axis=0)
    if n_mics > 1 and p["mic2_delay_ms"] > 0:
        dl = int(round(p["mic2_delay_ms"] * 1e-3 * sr))
        h[:, 1] = np.concatenate([np.zeros(dl), h[:-dl, 1]]) if dl > 0 else h[:, 1]
    # fade the last 5 % (the IR is ~-120 dB there anyway) and normalise.  md['scale'] converts back to the
    # continuous-time transfer function in units of the target envelope G (0 dB = mean level at 1 kHz):
    #   H(f) = rfft(h)[f] / (md['scale'] * sr)
    nf = max(1, N // 20)
    h[-nf:] *= np.cos(0.5 * np.pi * np.arange(nf) / nf)[:, None] ** 2
    scale = 1.0 / np.sqrt(np.mean(np.sum(h ** 2, axis=0)))
    md["scale"] = scale
    return h * scale, md


# ----------------------------------------------------------------------------------------------------------
# room: early reflections + 8-line FDN
# ----------------------------------------------------------------------------------------------------------
@njit(cache=True)
def _fdn(x, delays, g, pole, outL, outR, N):
    nl = delays.shape[0]
    maxd = 0
    for i in range(nl):
        if delays[i] > maxd:
            maxd = delays[i]
    buf = np.zeros((nl, maxd + 1))
    idx = np.zeros(nl, dtype=np.int64)
    lp = np.zeros(nl)
    yo = np.zeros((N, 2))
    v = np.zeros(nl)
    w = np.zeros(nl)
    sc = 1.0 / np.sqrt(nl)
    for n in range(N):
        xin = x[n] if n < x.shape[0] else 0.0
        for i in range(nl):
            j = idx[i] - delays[i]
            if j < 0:
                j += maxd + 1
            s = buf[i, j]
            # Jot absorption filter: one-pole low-pass with DC gain g_i
            lp[i] = g[i] * (1.0 - pole[i]) * s + pole[i] * lp[i]
            v[i] = lp[i]
        yl = 0.0
        yr = 0.0
        for i in range(nl):
            yl += outL[i] * v[i]
            yr += outR[i] * v[i]
        yo[n, 0] = yl
        yo[n, 1] = yr
        # fast Walsh-Hadamard transform (nl = 8), orthonormal
        for i in range(nl):
            w[i] = v[i]
        h = 1
        while h < nl:
            for i in range(0, nl, 2 * h):
                for j in range(i, i + h):
                    a = w[j]
                    b = w[j + h]
                    w[j] = a + b
                    w[j + h] = a - b
            h *= 2
        for i in range(nl):
            val = w[i] * sc + xin
            if abs(val) < 1e-30:
                val = 0.0
            buf[i, idx[i]] = val
            idx[i] += 1
            if idx[i] > maxd:
                idx[i] = 0
    return yo


def room_reverb(x, sr, t60=0.55, t60_hf=0.30, predelay_ms=8.0, seed=0):
    """Light small-room reverb of a mono or stereo signal -> stereo wet signal (same length), unit-less.
    Early reflections (6 per channel, 5-24 ms, low-passed) + 8-line Hadamard FDN with Jot absorption filters."""
    x = np.asarray(x, float)
    mono = x if x.ndim == 1 else x.mean(axis=1)
    rng = np.random.default_rng(seed + 1000)
    N = mono.size
    pd = int(predelay_ms * 1e-3 * sr)
    # early reflections
    er = np.zeros((N, 2))
    lp = ss.butter(1, 6000.0, fs=sr, output="sos")
    xl = ss.sosfilt(lp, mono)
    for c in range(2):
        taps = np.sort(rng.uniform(5e-3, 24e-3, 6))
        gains = 0.55 * (5e-3 / taps) ** 0.7 * rng.uniform(0.7, 1.0, 6)
        for tt, gg in zip(taps, gains):
            dl = pd + int(tt * sr)
            if dl < N:
                er[dl:, c] += gg * xl[:N - dl]
    # late reverb
    base = np.array([443, 557, 673, 787, 911, 1031, 1153, 1277], float) * sr / 44100.0
    delays = np.round(base).astype(np.int64)
    g = 10 ** (-3.0 * delays / (sr * t60))
    alpha = t60_hf / t60
    pole = np.log(10) / 4 * np.log10(g) * (1 - 1 / alpha ** 2)     # Jot (1991) one-pole absorption
    pole = np.clip(pole, 0.0, 0.99)
    outL = rng.choice([-1.0, 1.0], 8) / np.sqrt(8)
    outR = rng.choice([-1.0, 1.0], 8) / np.sqrt(8)
    outR[0] = -outL[0] if np.allclose(outL, outR) else outR[0]
    xin = np.concatenate([np.zeros(pd + int(12e-3 * sr)), mono])[:N]
    late = _fdn(np.ascontiguousarray(xin), delays, g, pole, outL, outR, N)
    # balance: late energy ~ 2x early energy (small room, listener near the instrument)
    e_er = np.sum(er ** 2) + 1e-30
    e_late = np.sum(late ** 2) + 1e-30
    late *= np.sqrt(2.0 * e_er / e_late)
    return er + late


