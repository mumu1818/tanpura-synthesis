def _rms(x, sr, t=2.0):
    seg = x[: max(1, int(t * sr))]
    return float(np.sqrt(np.mean(seg ** 2)))


def _finish(y, ref, sr, normalize):
    y = np.where(np.abs(y) < 1e-30, 0.0, y)            # no denormals
    if not np.all(np.isfinite(y)):
        raise FloatingPointError("non-finite output")
    if normalize:
        r_out = _rms(y, sr)
        if r_out > 0:
            y = y * (_rms(ref, sr) / r_out)
    return y


def _convolve(x, h):
    if h.ndim == 1:
        return ss.oaconvolve(x, h)[: x.size]
    return np.stack([ss.oaconvolve(x, h[:, c])[: x.size] for c in range(h.shape[1])], axis=1)


def apply_body(force, sr, preset="tanpura", stereo=False, room=0.0, seed=0, tail=0.0, normalize=True,
               return_ir=False, **overrides):
    """Map a bridge-force signal (e.g. common.to_audio(r['Fbridge'], fs), any scale) to radiated sound.

    preset   : 'tanpura' (male, large tumba; default), 'tanpura_small' (female/smaller), 'none' (pass-through),
               or a parameter dict.  Any preset parameter can be overridden by keyword (see PRESETS).
    stereo   : False -> 1-D array; True -> (N, 2) array, two mic positions (same body poles, different residues).
    room     : 0..1 wet amount of a light small-room reverb (0 = dry/anechoic; 1 = wet RMS equal to dry RMS).
    seed     : seed for the random dense modes (a different seed = a different instrument of the same type).
    tail     : seconds of silence appended to the input before filtering, so body/room tails are kept.
    normalize: scale the output so its RMS over the first 2 s equals that of the input (fair A/B).
    """
    x = np.asarray(force, float)
    if x.ndim != 1:
        raise ValueError("force must be 1-D")
    if tail > 0:
        x = np.concatenate([x, np.zeros(int(tail * sr))])
    p = get_params(preset, **overrides)
    ir = None
    if p.get("none"):
        y = np.stack([x, x], 1) if stereo else x.copy()
    else:
        ir, _md = body_ir(p, sr, seed, 2 if stereo else 1)
        y = _convolve(x, ir if stereo else ir[:, 0])
    if room > 0:
        rp = PRESETS["tanpura"] if p.get("none") else p
        wet = room_reverb(y, sr, rp["room_t60"], rp["room_t60_hf"], rp["room_predelay_ms"], seed)
        ydry = y if y.ndim == 2 else y[:, None]
        wet *= _rms(ydry, sr) / max(_rms(wet, sr), 1e-30)
        y = ydry + room * wet
        if not stereo:
            y = y.mean(axis=1)
    y = _finish(y, x, sr, normalize)
    return (y, ir) if return_ir else y


def prepare_ir(ir, sr, onset_db=-30.0, margin_ms=1.0, max_len_s=2.0, fade_ms=50.0, hp_hz=20.0):
    """Clean up a measured IR: high-pass (DC/rumble), cut leading silence up to `margin_ms` before the onset
    (first sample within onset_db of the peak), truncate to max_len_s with a half-Hann fade of fade_ms.
    Works on (N,) or (N, C)."""
    h = np.asarray(ir, float)
    h2 = h if h.ndim == 2 else h[:, None]
    if hp_hz:
        h2 = ss.sosfilt(ss.butter(2, hp_hz, "highpass", fs=sr, output="sos"), h2, axis=0)
    env = np.max(np.abs(h2), axis=1)
    i0 = int(np.argmax(env >= env.max() * 10 ** (onset_db / 20)))
    i0 = max(0, i0 - int(margin_ms * 1e-3 * sr))
    h2 = h2[i0: i0 + int(max_len_s * sr)].copy()
    nf = min(int(fade_ms * 1e-3 * sr), h2.shape[0] // 2)
    if nf > 0:
        h2[-nf:] *= np.cos(0.5 * np.pi * np.arange(nf) / nf)[:, None] ** 2
    return h2 if h.ndim == 2 else h2[:, 0]


def apply_ir(force, ir, sr, ir_sr=None, prepare=True, normalize=True, tail=0.0, room=0.0, seed=0):
    """Convolve the bridge force with a MEASURED bridge-to-microphone impulse response.

    ir     : (N,) mono or (N, 2) stereo IR (e.g. sf.read('my_tanpura_ir.wav')[0]).
    ir_sr  : sample rate of the IR if different from sr (band-limited resampling).
    prepare: run prepare_ir (HP, trim leading silence, fade the tail).
    The output is RMS-matched to the input over the first 2 s (normalize=True)."""
    x = np.asarray(force, float)
    if tail > 0:
        x = np.concatenate([x, np.zeros(int(tail * sr))])
    h = np.asarray(ir, float)
    if ir_sr is not None and int(ir_sr) != int(sr):
        g = np.gcd(int(ir_sr), int(sr))
        h = ss.resample_poly(h, int(sr) // g, int(ir_sr) // g, axis=0)
    if prepare:
        h = prepare_ir(h, sr)
    y = _convolve(x, h)
    if room > 0:
        rp = PRESETS["tanpura"]
        wet = room_reverb(y, sr, rp["room_t60"], rp["room_t60_hf"], rp["room_predelay_ms"], seed)
        ydry = y if y.ndim == 2 else y[:, None]
        wet *= _rms(ydry, sr) / max(_rms(wet, sr), 1e-30)
        y = ydry + room * wet
        if h.ndim == 1:
            y = y.mean(axis=1)
    return _finish(y, x, sr, normalize)


