def get_params(preset="tanpura", **overrides):
    if isinstance(preset, dict):
        p = dict(preset)
    else:
        if preset not in PRESETS:
            raise ValueError(f"unknown preset {preset!r}; choose from {list(PRESETS)}")
        p = dict(PRESETS[preset])
    unknown = [k for k in overrides if k not in p and not p.get("none")]
    if unknown:
        raise TypeError(f"unknown body parameter(s) {unknown}; valid: {sorted(p)}")
    p.update(overrides)
    return p


