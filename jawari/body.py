def _flex_rigidity(E, h, nu):
    return E * h ** 3 / (12.0 * (1.0 - nu ** 2))


def derived(p):
    """Derived physical quantities (areas, rigidities, coincidence frequencies, modal densities...)."""
    a = p["tabli_diam"] / 2
    S = np.pi * a ** 2
    P = 2 * np.pi * a
    rh = p["tabli_rho"] * p["tabli_h"]
    DL = _flex_rigidity(p["tabli_EL"], p["tabli_h"], p["nu"])
    DR = _flex_rigidity(p["tabli_ER"], p["tabli_h"], p["nu"])
    Deff = np.sqrt(DL * DR)
    fcL = C_AIR ** 2 / (2 * np.pi) * np.sqrt(rh / DL)
    fcR = C_AIR ** 2 / (2 * np.pi) * np.sqrt(rh / DR)
    n_plate = S / 2 * np.sqrt(rh / Deff)
    Zp = 8 * np.sqrt(Deff * rh)
    # shell
    R = p["gourd_diam"] / 2
    Ss = p["shell_area_frac"] * 4 * np.pi * R ** 2
    rhs = p["shell_rho"] * p["shell_h"]
    Ds = _flex_rigidity(p["shell_E"], p["shell_h"], p["nu"])
    n_shell_inf = Ss / 2 * np.sqrt(rhs / Ds)
    cL = np.sqrt(p["shell_E"] / (p["shell_rho"] * (1 - p["nu"] ** 2)))
    f_ring = cL / (2 * np.pi * R)
    # cavity
    V = p["gourd_fill"] * np.pi * p["gourd_diam"] ** 3 / 6 + p["neck_volume"]
    Scav = Ss + S
    f_cav1 = 2.0816 * C_AIR / (2 * np.pi * R)          # first non-Helmholtz mode of a rigid sphere (l=1)
    return dict(S=S, P=P, rh=rh, DL=DL, DR=DR, Deff=Deff, fcL=fcL, fcR=fcR, n_plate=n_plate, Zp=Zp,
                f_mass=Zp / (2 * np.pi * p["bridge_mass"]), Ss=Ss, n_shell_inf=n_shell_inf, f_ring=f_ring,
                V=V, Scav=Scav, f_cav1=f_cav1)


def _maidanik(f, fc, P, S, smax=3.0):
    """Radiation efficiency of a baffled thin plate (Maidanik 1962 / Beranek & Ver form)."""
    f = np.asarray(f, float)
    sig = np.empty_like(f)
    lam_c = C_AIR / fc
    lo = f < fc
    al = np.sqrt(f[lo] / fc)
    g1 = np.where(al < 1 / np.sqrt(2), (4 / np.pi ** 4) * (1 - 2 * al ** 2) / (al * np.sqrt(1 - al ** 2)), 0.0)
    g2 = (1 / (4 * np.pi ** 2)) * ((1 - al ** 2) * np.log((1 + al) / (1 - al)) + 2 * al) / (1 - al ** 2) ** 1.5
    sig[lo] = (lam_c ** 2 / S) * 2 * g1 + (P * lam_c / S) * g2
    hi = ~lo
    sig[hi] = 1.0 / np.sqrt(np.maximum(1 - fc / f[hi], 1e-12))
    return np.minimum(sig, smax)


def sigma_rad(f, d):
    """Orthotropic tabli: average the Maidanik efficiency over coincidence frequencies between the
    along-grain and cross-grain values (log-spaced). Smooths the coincidence transition over ~1.5 octaves."""
    fcs = np.geomspace(d["fcL"], d["fcR"], 9)
    return np.mean([_maidanik(f, fc, d["P"], d["S"]) for fc in fcs], axis=0)


def eta_plate(f, p, d):
    f = np.asarray(f, float)
    eta_int = p["eta0"] * (f / 1000.0) ** p["eta_exp"]
    eta_rad = RHO_AIR * C_AIR * sigma_rad(f, d) / (d["rh"] * 2 * np.pi * f)
    return eta_int + eta_rad


def envelope_db(f, p, d=None):
    """Target mean power response 10 log10 G^2(f) of the dense region, 0 dB at 1 kHz (SEA estimate)."""
    d = d or derived(p)

    def g2(ff):
        ff = np.asarray(ff, float)
        reY = d["Zp"] / (d["Zp"] ** 2 + (2 * np.pi * ff * p["bridge_mass"]) ** 2)
        return sigma_rad(ff, d) * reY / (ff * eta_plate(ff, p, d))

    return 10 * np.log10(g2(f) / g2(np.array([1000.0]))[0])


def densities(f, p, d):
    """Weyl modal densities [modes/Hz] of the three families (before the max_density cap)."""
    f = np.asarray(f, float)
    n_pl = np.full_like(f, d["n_plate"])
    n_sh = d["n_shell_inf"] * np.sqrt(np.minimum(f / d["f_ring"], 1.0))
    n_cv = 4 * np.pi * d["V"] * f ** 2 / C_AIR ** 3 + np.pi * d["Scav"] * f / (2 * C_AIR ** 2)
    n_cv = np.where(f >= d["f_cav1"], n_cv, 0.0)
    return dict(plate=n_pl, shell=n_sh, cav=n_cv)


def _smoothstep_log(f, f0, f1):
    x = np.clip(np.log(np.maximum(f, 1e-9) / f0) / np.log(f1 / f0), 0.0, 1.0)
    return x * x * (3 - 2 * x)


