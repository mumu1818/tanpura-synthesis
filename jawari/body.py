def _selftest():
    sr = 44100
    res = []

    def check(name, ok, msg):
        res.append((name, bool(ok), msg))
        print(f"[{'PASS' if ok else 'FAIL'}] {name}: {msg}")

    # 1. single explicit mode: measured peak frequency and Q of the IR's spectrum match the parameters
    one = [("test", "plate", 300.0, 25.0, 0.0, 1)]
    h, md = body_ir("tanpura", sr, 0, 1, modes=one, share_plate=0.0, share_shell=0.0, share_cav=0.0,
                    hp_hz=0, explicit_lp_hz=0, ir_dur=2.0)
    nfft = 1 << 20
    H = np.abs(np.fft.rfft(h[:, 0], nfft)) ** 2
    fr = np.fft.rfftfreq(nfft, 1 / sr)
    ip = np.argmax(H)
    above = np.where(H >= H[ip] / 2)[0]
    q = fr[ip] / (fr[above[-1]] - fr[above[0]])
    fpk = 300.0 / np.sqrt(1 - 2 * (1 / 50.0) ** 2)       # peak of the acceleration-type response
    check("single mode f/Q", abs(fr[ip] - fpk) < 0.2 and abs(q / 25 - 1) < 0.02,
          f"peak {fr[ip]:.2f} Hz ({fpk:.2f}), Q {q:.2f} (25)")
    # ... and its peak height equals the requested gain (0 dB re G) in the continuous-time units
    pk = 10 * np.log10(H[ip]) - 20 * np.log10(md["scale"] * sr)
    check("single mode peak gain", abs(pk) < 0.1, f"{pk:+.3f} dB (0)")
    # 2. dense region: E|H|^2 follows the SEA target envelope (averaged over 8 seeds, octave bands)
    errs = []
    acc = None
    for sd in range(8):
        h, md = body_ir("tanpura", sr, sd, 1, modes=[], hp_hz=0, dense_hp_hz=0)
        m2 = np.abs(np.fft.rfft(h[:, 0], 1 << 17)) ** 2
        acc = m2 if acc is None else acc + m2
    f = np.fft.rfftfreq(1 << 17, 1 / sr)
    tgt = 10 ** (envelope_db(np.maximum(f, 1.0), md["params"]) / 10)
    ref = np.mean(acc[(f > 2000) & (f < 2800)]) / np.mean(tgt[(f > 2000) & (f < 2800)])
    for fc in (2000, 4000, 8000, 12000):
        b = (f > fc / np.sqrt(2)) & (f < fc * np.sqrt(2))
        errs.append(10 * np.log10(np.mean(acc[b]) / ref / np.mean(tgt[b])))
    check("dense mean power vs SEA target", np.max(np.abs(errs)) < 1.5,
          "octave errors " + ", ".join(f"{e:+.2f}" for e in errs) + " dB (2/4/8/12 kHz)")
    # 3. causality / no pre-ringing; RMS match; finite; no DC
    rng = np.random.default_rng(1)
    x = np.zeros(3 * sr)
    x[sr // 2:] = rng.standard_normal(x.size - sr // 2) * np.exp(-np.arange(x.size - sr // 2) / sr)
    for st, rm in ((False, 0.0), (True, 0.0), (True, 0.5)):
        y = apply_body(x, sr, stereo=st, room=rm)
        pre = np.max(np.abs(y[: sr // 2])) / np.max(np.abs(y))      # FFT round-off only (~1e-16)
        r_in, r_out = _rms(x, sr), _rms(y, sr)
        check(f"apply_body stereo={st} room={rm}",
              pre < 1e-12 and abs(r_out / r_in - 1) < 1e-9 and np.all(np.isfinite(y)),
              f"max |y| before input onset = {20 * np.log10(pre + 1e-300):.0f} dB re peak (causal), "
              f"RMS ratio {r_out / r_in:.6f}, shape {y.shape}")
    # 4. preset 'none' is a pass-through, apply_ir with a delta is identity
    y = apply_body(x, sr, preset="none")
    check("preset none", np.allclose(y, x), "identity")
