def frac_oct_smooth(f, mag2, frac=6):
    """1/frac-octave power smoothing of |H|^2 on an rfft grid."""
    out = np.empty_like(mag2)
    lo = f * 2 ** (-0.5 / frac)
    hi = f * 2 ** (0.5 / frac)
    c = np.concatenate([[0.0], np.cumsum(mag2)])
    il = np.searchsorted(f, lo)
    ih = np.searchsorted(f, hi, side="right")
    ih = np.maximum(ih, il + 1)
    out[:] = (c[np.minimum(ih, f.size)] - c[il]) / (np.minimum(ih, f.size) - il)
    return out


def band_t60(h, sr, centres=(125, 250, 500, 1000, 2000, 4000, 8000)):
    """T60 per octave band of an IR (Schroeder EDC, fit -5..-25 dB, i.e. T20 x 3)."""
    out = {}
    for fc in centres:
        if fc * np.sqrt(2) >= sr / 2:
            continue
        sos = ss.butter(3, [fc / np.sqrt(2), fc * np.sqrt(2)], "bandpass", fs=sr, output="sos")
        hb = ss.sosfilt(sos, h)
        out[fc] = edc_decay(hb, sr, -5, -25) * 3.0
    return out


def edc_decay(x, sr, a_db=-5.0, b_db=-35.0):
    """Time [s] for the Schroeder energy decay curve to fall from a_db to b_db (from its start)."""
    e = np.cumsum((x[::-1]) ** 2)[::-1]
    e = 10 * np.log10(e / e[0] + 1e-300)
    ia = np.argmax(e <= a_db)
    ib = np.argmax(e <= b_db)
    if ib <= ia:
        return float("nan")
    t = np.arange(ia, ib) / sr
    k = np.polyfit(t, e[ia:ib], 1)[0]                  # dB/s
    return float((b_db - a_db) / k)


