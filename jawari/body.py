def exp_sweep(f1=20.0, f2=20000.0, dur=10.0, sr=48000, fade_s=0.05):
    """Exponential sine sweep (Farina 2000) and its inverse filter. Play `sweep` into a small shaker / exciter
    on the bridge (strings damped), record the mic, then ir_from_sweep(rec, inv, sr)."""
    t = np.arange(int(dur * sr)) / sr
    R = np.log(f2 / f1)
    sweep = np.sin(2 * np.pi * f1 * dur / R * (np.exp(t * R / dur) - 1))
    nf = int(fade_s * sr)
    win = np.ones_like(sweep)
    win[:nf] = np.sin(0.5 * np.pi * np.arange(nf) / nf) ** 2
    win[-nf:] = np.cos(0.5 * np.pi * np.arange(nf) / nf) ** 2
    sweep *= win
    inv = sweep[::-1] * np.exp(-t * R / dur)       # amplitude-compensated time reverse (-6 dB/oct)
    # normalise so that sweep * inv has unit gain at the sweep's mid frequency
    fm = np.sqrt(f1 * f2)
    H = np.fft.rfft(ss.fftconvolve(sweep, inv))
    fr = np.fft.rfftfreq(2 * sweep.size - 1, 1 / sr)
    inv /= np.abs(H[np.argmin(np.abs(fr - fm))])
    return sweep, inv


def ir_from_sweep(recorded, inv, sr, ir_len_s=2.0):
    """Deconvolve a recorded sweep response; keeps the linear IR (harmonic distortion products land BEFORE it
    in time and are discarded)."""
    y = ss.fftconvolve(np.asarray(recorded, float), inv)
    i0 = inv.size - 1                                # zero-lag of the linear response
    return y[i0: i0 + int(ir_len_s * sr)]


def ir_from_tap(mic, sr, force=None, eps=1e-3, ir_len_s=2.0):
    """Impulse (tap) measurement. With an impact-hammer force signal: regularised spectral division
    H = M F* / (|F|^2 + eps max|F|^2). Without one (pencil / small steel-ball tap): the onset-aligned mic signal
    is used as the IR (valid up to the tap's bandwidth, roughly 1 / contact-time)."""
    m = np.asarray(mic, float)
    if force is None:
        return prepare_ir(m, sr, max_len_s=ir_len_s)
    f = np.asarray(force, float)
    n = int(2 ** np.ceil(np.log2(m.size + f.size)))
    M = np.fft.rfft(m, n)
    F = np.fft.rfft(f, n)
    H = M * np.conj(F) / (np.abs(F) ** 2 + eps * np.max(np.abs(F) ** 2))
    return np.fft.irfft(H, n)[: int(ir_len_s * sr)]


def ir_from_wire_break(mic, sr, ir_len_s=2.0):
    """Wire-break method (a thin copper wire looped over the bridge is pulled until it snaps: a force STEP).
    The impulse response is the time derivative of the recorded step response."""
    m = prepare_ir(np.asarray(mic, float), sr, max_len_s=ir_len_s + 0.01, hp_hz=0)
    return np.diff(m, prepend=0.0)[: int(ir_len_s * sr)]


