"""Tanpura body / radiation model: bridge force -> radiated sound (one-way output filter).

    from body import apply_body
    y = apply_body(force_44k, 44100)                          # mono, default male tanpura body, dry
    y = apply_body(force_44k, 44100, stereo=True, room=0.3)   # two 'mic positions' + light room
    y = apply_ir(force_44k, measured_ir, 44100)               # a MEASURED bridge-to-mic impulse response

Model (see BODY.md for sources and which numbers are assumptions)
------------------------------------------------------------------
The bridge-force -> microphone-pressure transfer function is written as a sum of real normal modes,

    dense modes:     h_k(t) = A_k exp(-sigma_k t) sin(omega_dk t)
    explicit modes:  h_k(t) = -(A_k / omega_k^2) d^2/dt^2 [exp(-sigma_k t) sin(omega_dk t)]   (acceleration form:
                     far-field pressure of a monopole-like mode, +12 dB/oct below the mode, flat above)

all for t >= 0 only, i.e. strictly causal: nothing precedes the force that causes it (no pre-ringing).

1. Explicit low modes (~80 Hz - 1.5 kHz): air/neck mode A0, tabli breathing mode T1, tabli rocking/ring modes,
   first gourd-cavity mode A1 ... each with (frequency, Q, peak gain re the mean high-frequency level, mic-2 factor).
2. Dense region (from ~0.5 kHz up): seeded-random modes from three families whose modal densities follow
   Weyl's law for the actual geometry:
       tabli (thin orthotropic plate)  n = S/2 sqrt(rho h / D)              (constant in f)
       gourd shell                     n -> plate value above the ring frequency, ~sqrt(f) below
       gourd air cavity                n = 4 pi V f^2 / c^3 + pi S f / (2 c^2)  (grows as f^2)
   so the total modal density grows with frequency. Frequencies are drawn by inverting the cumulative mode
   count N(f) with jitter (mode spacings are neither regular nor Poisson); residues are Gaussian (product of
   random mode-shape values at bridge and mic), damping is frequency dependent
       eta(f) = eta0 (f/1kHz)^p + eta_rad(f),
   with a log-normal mode-to-mode scatter. Per-mode amplitudes are set so that the EXPECTED power response
   E|H(f)|^2 equals a target envelope G(f)^2 from a statistical-energy (SEA) argument:
       G^2(f) ~ sigma_rad(f) Re{Y_bridge(f)} / (f eta(f))
   sigma_rad = Maidanik radiation efficiency of the tabli, averaged over the along- and cross-grain coincidence
   frequencies (orthotropic wood); Y_bridge = 1/(Z_plate + j omega m_bridge), Z_plate = 8 sqrt(D rho h).
3. Stereo: TWO microphones see the SAME poles (same body) with different residues: explicit mode (m, n) gets
   the factor cos(m * mic_spread_deg) at mic 2 (mic 2 rotated about the tabli normal), dense-mode residues are
   drawn with a small inter-mic correlation rho_mics.
4. Room (optional, room = 0..1 wet amount): early reflections + an 8-line feedback delay network with
   frequency-dependent T60 (Jot absorption filters). Dry by default.
Output is RMS-matched to the input over the first 2 s so A/B comparisons are loudness-fair.

The body does NOT feed back on the string (no bridge admittance in the string model yet); see BODY.md.
"""
