def explicit_modes(p):
    """[(name, family, f, Q, gain_dB, mic2_factor), ...] from the preset parameters (see comment above)."""
    dpsi = np.deg2rad(p["mic_spread_deg"])
    out = [("A0 air/neck", "air", p["a0_hz"], p["a0_q"], p["a0_gain_db"], 1.0)]
    g0 = {1: 0.0, 2: -6.0, 3: -9.0}
    for (m, n), lam in LEISSA_CLAMPED:
        f = p["t1_hz"] * (lam / LEISSA_CLAMPED[0][1]) ** p["gamma"]
        if f > p["explicit_fmax"]:
            continue
        q = min(p["t1_q"] * (f / p["t1_hz"]) ** 0.3, 50.0)
        g = p["t1_gain_db"] + g0[n] if m == 0 else max(6.0 - (m - 1) - 1.5 * (n - 1), 1.0)
        out.append((f"T({m},{n})", "plate", f, q, g, float(np.cos(m * dpsi))))
    f_a1 = 2.0816 * C_AIR / (np.pi * p["gourd_diam"])
    out.append(("A1 cavity", "air", f_a1, p["a1_q"], p["a1_gain_db"], float(np.cos(dpsi))))
    return out


